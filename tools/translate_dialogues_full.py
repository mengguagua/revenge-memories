def main():
    hubs=json.loads((ROOT/'data/hubs.json').read_text())['dialogues']
    opening=json.loads((ROOT/'data/opening.json').read_text())['dialogues_by_label']
    result={}
    for key,group in hubs.items():
        old=opening.get(group['source']['label'],[])
        if len(old)==len(group['pages']) and all('text_zh' in p for p in old):
            result[key]=[p['text_zh'] for p in old]
        if int(key) in TRANSLATIONS:
            texts=TRANSLATIONS[int(key)].splitlines()
            assert len(texts)==len(group['pages']),(key,len(texts),len(group['pages']))
            result[key]=texts
    (ROOT/'data/dialogue_zh.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    missing=[k for k in hubs if k not in result]
    print('Translated',len(result),'groups;',sum(len(v) for v in result.values()),'pages; missing',missing)
if __name__=='__main__':main()
